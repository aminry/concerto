#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn pool_meets_size_floor() {
        // Task 20 spec: 200+ names. We comfortably exceed that.
        assert!(
            COMPOSERS.len() >= 200,
            "COMPOSERS pool must hold at least 200 names; has {}",
            COMPOSERS.len()
        );
    }

    #[test]
    fn every_name_is_slug_safe() {
        // Each entry must be plain ASCII lowercase alphanumerics — the
        // string doubles as a filesystem path segment in
        // `<workspace.slug>/<composer>/`.
        for name in COMPOSERS {
            assert!(!name.is_empty(), "empty composer name in pool");
            assert!(
                name.chars()
                    .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit()),
                "composer name {name:?} must be ASCII lowercase letters/digits only"
            );
        }
    }

    #[test]
    fn first_few_are_canonical_bach_mozart() {
        // The order is frozen; the leading entries are the canonical
        // "first workarea gets `bach`" UX expectation.
        assert_eq!(COMPOSERS[0], "bach");
        assert!(COMPOSERS.contains(&"mozart"));
        assert!(COMPOSERS.contains(&"beethoven"));
        assert!(COMPOSERS.contains(&"chopin"));
        assert!(COMPOSERS.contains(&"debussy"));
    }

    /// Allocation uses `Vec<&str>::iter().enumerate().find(...)` — confirm
    /// the lowest-index unused name is selected.
    #[test]
    fn lowest_unused_index_is_chosen() {
        let used: HashSet<&str> = ["bach", "mozart"].into_iter().collect();
        let pick = COMPOSERS
            .iter()
            .find(|n| !used.contains(*n))
            .copied()
            .expect("pool not exhausted");
        // Whatever comes immediately after the first two indices we marked
        // used.
        let expected = COMPOSERS
            .iter()
            .find(|n| !used.contains(*n))
            .copied()
            .unwrap();
        assert_eq!(pick, expected);
        // It must NOT be either of the used ones.
        assert!(!used.contains(pick));
    }
}
