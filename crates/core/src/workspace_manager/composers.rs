//! Composer-name allocation pool (Task 20, design/03 §3.5).
//!
//! Per-workspace, every workarea is named after a classical composer:
//! `bach`, `mozart`, `beethoven`, … The Workspace Manager picks the
//! lowest-indexed name in [`COMPOSERS`] that is not already in use within
//! the workspace, and falls back to `<composer>-N` once the pool is
//! exhausted.
//!
//! ## Public-interface contract
//!
//! - The order of [`COMPOSERS`] is FROZEN by Task 20. Adding new names at
//!   the END of the slice is fine (they will be picked only after every
//!   earlier name is taken); reordering or removing names changes which
//!   composer the Workspace Manager hands out for a fresh workspace,
//!   which the UI persists. Treat reordering as a breaking change.
//! - Names are plain ASCII lowercase. Diacritics are stripped so the
//!   strings double as URL-safe filesystem path segments (the workarea
//!   directory is `<workspace.slug>/<composer>/`).
//!
//! ## Why this many
//!
//! Empirically a power user might spin up dozens of workareas inside one
//! workspace over the lifetime of a project. We ship ~500 composer names
//! so the `-2` overflow path stays a pure tail case. The total comfortably
//! exceeds the task spec's 200+ floor.

